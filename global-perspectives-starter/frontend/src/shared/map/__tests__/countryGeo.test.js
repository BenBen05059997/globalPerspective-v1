import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ISO3_TO_NUM } from '@/shared/map/countryGeo.js';
import { buildIso3ToNum, render } from '../../../../../../scripts/gen-country-geo.mjs';

const MAP_DIR = resolve(import.meta.dirname, '..');
const topology = JSON.parse(readFileSync(resolve(MAP_DIR, 'countries-110m.json'), 'utf8'));

describe('countryGeo (generated by scripts/gen-country-geo.mjs)', () => {
  it('resolves every bundle country except the deliberate skips', () => {
    expect(buildIso3ToNum(topology).unresolved).toEqual([]);
  });
  it('joins known ISO3 codes to their numeric ids, including formerly missing ones', () => {
    const known = { USA: '840', FRA: '250', ISL: '352', EST: '233', GRL: '304', BWA: '072', CIV: '384', SSD: '728', COD: '180', ESH: '732', GNQ: '226', SLB: '090', BIH: '070' };
    for (const [iso3, num] of Object.entries(known)) expect(ISO3_TO_NUM[iso3]).toBe(num);
  });
  it('is the committed output of the generator', () => {
    expect(readFileSync(resolve(MAP_DIR, 'countryGeo.js'), 'utf8')).toBe(render(buildIso3ToNum(topology).map));
  });
});
