#!/usr/bin/env node
/**
 * Regenerates global-perspectives-starter/frontend/src/shared/map/countryGeo.js.
 *
 * Reads the topojson bundle (shared/map/countries-110m.json: numeric feature `id` + `properties.name`),
 * resolves every feature name to an ISO3 through the one country table (backend/shared/src/countries.js,
 * identical to the frontend resolver), and writes ISO3_TO_NUM. ISO3_CENTROID_FALLBACK (countries absent
 * from the 110m mesh) is hand-kept below.
 *
 *   node scripts/gen-country-geo.mjs           # write countryGeo.js
 *   node scripts/gen-country-geo.mjs --check   # exit 1 if the file is out of date
 *
 * Antarctica, N. Cyprus and Somaliland are skipped (SKIP). Exits 1 and lists the names when a bundle feature does not resolve (add an alias to iso3Names.json
 * in both copies, then rerun).
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'global-perspectives-starter/frontend/src/shared/map/countryGeo.js');
const BUNDLE = path.join(ROOT, 'global-perspectives-starter/frontend/src/shared/map/countries-110m.json');
const { resolveCountry } = createRequire(import.meta.url)(path.join(ROOT, 'backend/shared/src/countries.js'));

// Tiny/absent-in-110m countries: manual centroids [lon, lat] so arcs still land.
const CENTROID_FALLBACK = { XKX: [20.9, 42.6], BHR: [50.55, 26.05], SSD: [31.3, 7.0], SGP: [103.82, 1.35] };

// Bundle features that are not countries in the table (territories / disputed areas): skipped on purpose.
const SKIP = new Set(['Antarctica', 'N. Cyprus', 'Somaliland']);

export function buildIso3ToNum(topology) {
  const map = {};
  const unresolved = [];
  for (const g of topology.objects.countries.geometries) {
    const name = g.properties?.name;
    if (SKIP.has(name)) continue;
    const iso3 = resolveCountry(name)?.iso3;
    if (!iso3) unresolved.push(`${g.id} ${name}`);
    else if (!(iso3 in map)) map[iso3] = String(g.id);
  }
  return { map, unresolved };
}

export function render(map) {
  const rows = Object.keys(map).sort().map((k) => `  ${k}: '${map[k]}',`).join('\n');
  const fb = Object.entries(CENTROID_FALLBACK).map(([k, v]) => `${k}: [${v[0]}, ${v[1]}]`).join(', ');
  return `// countryGeo — ISO-3 → topojson numeric id join + centroid fallbacks for countries absent from the
// 110m mesh. GENERATED by scripts/gen-country-geo.mjs from shared/map/countries-110m.json (feature names
// resolved through the one country table); do not hand-edit — rerun the script. Used by the map to draw
// spread arcs (origin→destination centroids) and tint affected-country polygons.

export const ISO3_TO_NUM = {
${rows}
};

// Tiny/absent-in-110m countries — manual centroids [lon, lat] so arcs still land.
export const ISO3_CENTROID_FALLBACK = {
  ${fb},
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { map, unresolved } = buildIso3ToNum(JSON.parse(fs.readFileSync(BUNDLE, 'utf8')));
  if (unresolved.length) {
    console.error(`Unresolved bundle names (add aliases to iso3Names.json):\n  ${unresolved.join('\n  ')}`);
    process.exit(1);
  }
  const text = render(map);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(OUT, 'utf8') !== text) { console.error('countryGeo.js is out of date: run node scripts/gen-country-geo.mjs'); process.exit(1); }
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${Object.keys(map).length} countries to ${path.relative(ROOT, OUT)}`);
  }
}
