#!/usr/bin/env node
// Generates project-docs/reference/*.md from the code and (unless --offline) read-only live AWS.
// The reference files are never hand-edited: change the code or AWS, then re-run this.
//
//   node scripts/gen-reference.mjs            # functions.json + source + live AWS (ap-northeast-1, read-only)
//   node scripts/gen-reference.mjs --offline  # functions.json + source only; no AWS calls
//
// AWS calls are list/get only. Environment variable VALUES never leave the AWS CLI: the query asks for
// keys(Environment.Variables), so only key names reach this process — except keys ending in TABLE, whose
// values are DynamoDB table names (features.md shows which tables a feature's Lambdas write).
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'project-docs/reference');
const SRC = join(ROOT, 'global-perspectives-starter/frontend/src');
const REGION = 'ap-northeast-1';
const OFFLINE = process.argv.includes('--offline');
const TODAY = new Date().toISOString().slice(0, 10);
const SHARED = 'backend/shared'; // the one copy of shared Lambda code; each consumer links it as src/_shared
const FUNCTIONS = JSON.parse(readFileSync(join(ROOT, 'scripts/functions.json'), 'utf8')).functions;
const NAMES = Object.keys(FUNCTIONS).sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }));

const run = promisify(execFile);
const aws = async (...args) => JSON.parse((await run('aws', [...args, '--region', REGION, '--output', 'json'], { maxBuffer: 16 << 20 })).stdout);
const fnName = (arn) => (arn || '').match(/:function:([^:]+)/)?.[1] || null;
const code = (s) => '`' + s + '`';
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');

function header(title, sources) {
  return `# ${title}\n\nGenerated by scripts/gen-reference.mjs on ${TODAY} — do not edit. Re-run \`node scripts/gen-reference.mjs\` after any change.\n\nSources: ${sources}. Mode: ${OFFLINE ? '**offline** (no AWS calls)' : `live AWS ${REGION}, read-only`}.\n`;
}

function walk(dir, exts) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((name) => {
    // src/_shared links to backend/shared/src: scanned once as SHARED, not once per Lambda.
    if (name === 'node_modules' || name === '_shared' || name.startsWith('.')) return [];
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return walk(p, exts);
    return exts.some((e) => name.endsWith(e)) ? [p] : [];
  });
}

const usesShared = (dir) => Boolean(dir) && existsSync(join(ROOT, dir, 'src/_shared'));
const lambdaSources = (dir) => (dir ? walk(join(ROOT, dir, 'src'), ['.js', '.mjs', '.cjs']).filter((f) => !/\.test\.|__tests__|\/test_/.test(f)) : []);

// ---------- live AWS (one place, so --offline skips all of it) ----------
// The AWS CLI auto-paginates list calls. Calls run 8 at a time (each CLI start costs seconds).
const pool = async (items, fn, n = 8) => {
  const out = new Array(items.length);
  let i = 0;
  await Promise.all(Array.from({ length: n }, async () => { while (i < items.length) { const k = i++; out[k] = await fn(items[k]); } }));
  return out;
};
let live = null;
if (!OFFLINE) {
  const known = new Set(NAMES);
  const fns = await aws('lambda', 'list-functions', '--query', 'Functions[].[FunctionName, Runtime]');
  const runtime = Object.fromEntries(fns);
  const unlisted = fns.map(([n]) => n).filter((n) => /^news/i.test(n) && !known.has(n)).sort();

  const envKeys = {};
  const url = {};
  const tables = {}; // lambda -> { ENV_KEY_ENDING_IN_TABLE: table name }
  await pool(NAMES, async (n) => {
    envKeys[n] = (await aws('lambda', 'get-function-configuration', '--function-name', n, '--query', 'keys(Environment.Variables || `{}`)')).sort();
    url[n] = (await aws('lambda', 'list-function-url-configs', '--function-name', n, '--query', 'FunctionUrlConfigs[].AuthType')) || [];
    const tableKeys = envKeys[n].filter((k) => /^[A-Z0-9_]+TABLE$/.test(k));
    tables[n] = tableKeys.length
      ? await aws('lambda', 'get-function-configuration', '--function-name', n, '--query', `{${tableKeys.map((k) => `${k}: Environment.Variables.${k}`).join(', ')}}`)
      : {};
  });

  const rules = await aws('events', 'list-rules', '--query', 'Rules[].{Name: Name, State: State, ScheduleExpression: ScheduleExpression, EventPattern: EventPattern}');
  const ruleRows = await pool(rules, async (rule) => {
    const targets = (await aws('events', 'list-targets-by-rule', '--rule', rule.Name, '--query', 'Targets[].Arn')).map(fnName).filter((t) => known.has(t));
    return targets.length ? { via: 'EventBridge rule', name: rule.Name, expr: rule.ScheduleExpression || rule.EventPattern || '', tz: 'UTC', state: rule.State, targets } : null;
  });
  const allSched = await aws('scheduler', 'list-schedules', '--query', 'Schedules[].{Name: Name, GroupName: GroupName, Arn: Target.Arn}');
  const sched = allSched.filter((s) => known.has(fnName(s.Arn)));
  const schedRows = await pool(sched, async (s) => {
    const d = await aws('scheduler', 'get-schedule', '--name', s.Name, '--group-name', s.GroupName, '--query', '{e: ScheduleExpression, tz: ScheduleExpressionTimezone, state: State}');
    return { via: 'Scheduler', name: s.Name, expr: d.e, tz: d.tz || 'UTC', state: d.state, targets: [fnName(s.Arn)] };
  });
  const schedules = [...ruleRows.filter(Boolean), ...schedRows];
  const otherRules = ruleRows.filter((r) => !r).length;
  const otherSchedules = allSched.length - sched.length;

  const bucket = (await aws('s3api', 'list-buckets', '--query', "Buckets[?starts_with(Name, 'globalperspective-world')].Name"))[0];
  const listPrefixes = async (prefix) => (await aws('s3api', 'list-objects-v2', '--bucket', bucket, '--delimiter', '/', '--prefix', prefix, '--query', 'CommonPrefixes[].Prefix')) || [];
  const tops = await listPrefixes('');
  const s3 = { bucket, tree: await pool(tops, async (top) => ({ top, children: await listPrefixes(top) })) };
  live = { runtime, unlisted, envKeys, url, tables, schedules, otherRules, otherSchedules, s3 };
}

const schedules = live ? live.schedules : NAMES.flatMap((n) => (FUNCTIONS[n].schedules || []).map((s) => ({
  via: s.via === 'scheduler' ? 'Scheduler' : 'EventBridge rule', name: s.name, expr: s.expr, tz: s.tz || 'UTC', state: s.state, targets: [n],
})));
schedules.sort((a, b) => a.targets[0].localeCompare(b.targets[0], 'en', { sensitivity: 'base' }) || a.name.localeCompare(b.name));

const files = {};

// ---------- lambdas.md ----------
{
  const rows = NAMES.map((n) => {
    const f = FUNCTIONS[n];
    const triggers = schedules.filter((s) => s.targets.includes(n)).map((s) => `${s.name} ${s.expr} (${s.state})`);
    if (live?.url[n]?.length) triggers.push(`Function URL (${live.url[n].join(', ')})`);
    let rt = f.runtime;
    if (live && live.runtime[n] && live.runtime[n] !== f.runtime) rt = `${live.runtime[n]} (functions.json says ${f.runtime})`;
    if (live && !live.runtime[n]) rt = `${f.runtime} — NOT FOUND LIVE`;
    const notes = [f.deployBlocked, f.nodeModules ? 'deployed zip ships node_modules' : ''].filter(Boolean).join(' ');
    return [code(n), f.dir ? code(`${f.dir}/src`) : '—', rt, f.group, triggers.join('; ') || (live ? '—' : 'schedules only (offline)'), notes];
  });
  const groups = [...new Set(NAMES.map((n) => FUNCTIONS[n].group))].sort();
  let md = header('Lambdas', '`scripts/functions.json`' + (live ? ', `aws lambda list-functions`, `list-function-url-configs`, `aws events`, `aws scheduler`' : ''));
  md += `\n${NAMES.length} functions in ${groups.length} groups (${groups.join(', ')}). Schedules: see schedules.md.\n\n`;
  md += table(['Deployed name', 'Repo source', 'Runtime', 'Group', 'Triggers', 'Notes'], rows) + '\n';
  if (live?.unlisted.length) md += `\nLive \`news*\` functions missing from functions.json: ${live.unlisted.map(code).join(', ')}.\n`;
  files['lambdas.md'] = md;
}

// ---------- schedules.md ----------
{
  let md = header('Schedules', live ? '`aws events list-rules` + `list-targets-by-rule`, `aws scheduler list-schedules` + `get-schedule`' : '`scripts/functions.json` (snapshot of live AWS)');
  md += `\nOnly rules/schedules that target a Lambda in functions.json. EventBridge rule expressions are UTC.\n\n`;
  md += table(['Target Lambda', 'Via', 'Name', 'Expression', 'Timezone', 'State'],
    schedules.map((s) => [s.targets.map(code).join(', '), s.via, s.name, code(s.expr), s.tz, s.state])) + '\n';
  const on = schedules.filter((s) => s.state === 'ENABLED').length;
  md += `\n${on} enabled, ${schedules.length - on} disabled.`;
  if (live) md += ` Skipped ${live.otherRules} EventBridge rules and ${live.otherSchedules} Scheduler schedules in the account that target nothing in functions.json (other projects).`;
  files['schedules.md'] = md + '\n';
}

// ---------- env-keys.md ----------
{
  const readInCode = (dir) => {
    const keys = new Set();
    for (const f of lambdaSources(dir)) for (const m of readFileSync(f, 'utf8').matchAll(/process\.env(?:\.([A-Z][A-Z0-9_]*)|\[\s*['"]([A-Z][A-Z0-9_]*)['"]\s*\])/g)) keys.add(m[1] || m[2]);
    return [...keys].sort();
  };
  // Set by the Lambda runtime itself, never in the function's env map.
  const AWS_RUNTIME_KEYS = new Set(['AWS_REGION', 'AWS_DEFAULT_REGION', 'AWS_LAMBDA_FUNCTION_NAME', 'AWS_LAMBDA_FUNCTION_VERSION', 'AWS_EXECUTION_ENV', 'LAMBDA_TASK_ROOT']);
  const sharedKeys = readInCode(SHARED);
  const lines = [`## Shared code (\`${SHARED}/src\`, linked as \`src/_shared\`)\n`,
    `- Reads: ${sharedKeys.length ? sharedKeys.map(code).join(', ') : '—'}. Listed once here: a Lambda that links it counts these as read, and they are not listed below as unset.`, ''];
  for (const n of NAMES) {
    const f = FUNCTIONS[n];
    const inCode = readInCode(f.dir);
    const readable = usesShared(f.dir) ? [...inCode, ...sharedKeys] : inCode;
    lines.push(`## ${n}\n`);
    if (live) {
      const set = live.envKeys[n];
      lines.push(`- Live keys: ${set.length ? set.map(code).join(', ') : '—'}`);
      if (f.dir) {
        const unread = set.filter((k) => !readable.includes(k));
        const unset = inCode.filter((k) => !set.includes(k) && !AWS_RUNTIME_KEYS.has(k));
        lines.push(`- Set live, not read in repo source: ${unread.length ? unread.map(code).join(', ') : '—'}`);
        lines.push(`- Read in repo source, not set live (code default applies): ${unset.length ? unset.map(code).join(', ') : '—'}`);
      }
    } else {
      lines.push(`- Read in repo source: ${inCode.length ? inCode.map(code).join(', ') : '—'}${usesShared(f.dir) ? ' (+ shared code)' : ''}`);
    }
    if (!f.dir) lines.push('- No repo source dir.');
    lines.push('');
  }
  let md = header('Lambda environment keys', (live ? '`aws lambda get-function-configuration --query keys(Environment.Variables)`, ' : '') + '`process.env.*` reads in each Lambda\'s `<dir>/src` (`dir` from `scripts/functions.json`)');
  md += '\nKey NAMES only — values are never fetched into this file. Some deployed zips differ from the repo (see lambdas.md notes), so "read in repo source" can lag the deployed code. Env names can be misleading (e.g. `GROK_*`/`XAI_*` may hold another provider) — check the live value before assuming.\n\n';
  files['env-keys.md'] = md + lines.join('\n');
}

// ---------- routes.md ----------
let routes;
{
  const app = readFileSync(join(SRC, 'app/App.jsx'), 'utf8');
  const legacy = readFileSync(join(SRC, 'app/LegacyRedirects.jsx'), 'utf8');
  const imports = {};
  for (const m of app.matchAll(/(?:import\s+(\w+)\s+from\s+'(@\/[^']+)')|(?:const\s+(\w+)\s*=\s*lazy\(\(\)\s*=>\s*import\('(@\/[^']+)'\)\))/g)) {
    imports[m[1] || m[3]] = { path: (m[2] || m[4]).replace(/^@\//, 'src/'), lazy: Boolean(m[3]) };
  }
  // Named imports: the LegacyRedirects components and feature public APIs (`import { Home } from '@/features/home'`).
  for (const m of app.matchAll(/import\s*\{([^}]+)\}\s*from\s*'(@\/[^']+)'/g)) {
    for (const name of m[1].split(',').map((s) => s.trim())) imports[name] = { path: m[2].replace(/^@\//, 'src/'), lazy: false };
  }
  const redirectTarget = {};
  for (const m of legacy.matchAll(/export function (\w+)\(\)\s*\{([\s\S]*?)\n\}/g)) {
    const to = m[2].match(/<Navigate[^>]*\bto="([^"]+)"/);
    redirectTarget[m[1]] = to ? `redirect → ${code(to[1])}` : 'redirect (computed; see source)';
  }
  redirectTarget.MapRedirect = 'redirect → `/` (keeps search + hash)';
  const inline = { Boom: 'deliberate crash (error-boundary test)', NotFound: '404 page' };

  routes = [...app.matchAll(/<Route\s+path="([^"]+)"\s+element=\{<(\w+)\b/g)].map((m) => {
    const comp = m[2];
    const imp = imports[comp];
    const feature = imp?.path.match(/^src\/features\/([^/]+)/)?.[1] || null;
    return { path: m[1], comp, file: imp ? imp.path : 'src/app/App.jsx (inline)', lazy: imp?.lazy, feature, kind: redirectTarget[comp] || inline[comp] || 'page' };
  });

  let md = header('Frontend routes', '`src/app/App.jsx`, `src/app/LegacyRedirects.jsx`');
  md += '\nPaths are relative to `global-perspectives-starter/frontend/`. Lazy = its own chunk (React.lazy).\n\n';
  md += table(['Path', 'Component', 'File', 'Lazy', 'Kind'], routes.map((r) => [code(r.path), r.comp, code(r.file), r.lazy ? 'yes' : 'no', r.kind])) + '\n';
  files['routes.md'] = md;
}

// ---------- s3-prefixes.md + features.md (features uses the S3 scan) ----------
{
  // Path-like string literals in Lambda code (comments and imports skipped). A literal counts when it looks
  // like a key (file extension, trailing slash or template) or shares its top segment with one that does;
  // MIME types, user agents, model ids and frontend paths are excluded.
  const NOT_S3 = /^(application|text|image|audio|video|multipart|features|shared|scripts|n)\/|\/\d|:|\.\.\./;
  const hits = [];
  for (const dir of [...NAMES.map((n) => FUNCTIONS[n].dir).filter(Boolean), SHARED]) {
    for (const f of lambdaSources(dir)) {
      for (const line of readFileSync(f, 'utf8').split('\n')) {
        if (/^\s*(import|\/\/|\*|\/\*)/.test(line)) continue;
        const lits = [
          ...[...line.matchAll(/['"]([a-z][a-z0-9_-]*\/[^'"\s]*)['"]/g)].map((m) => m[1]),
          ...[...line.matchAll(/`([a-z][a-z0-9_-]*\/[^`]*)`/g)].map((m) => m[1]),
          // env-overridable prefix defaults: process.env.SIGNALS_PREFIX || 'signals'
          ...[...line.matchAll(/process\.env\.[A-Z0-9_]*PREFIX[A-Z0-9_]*\s*\|\|\s*['"`]([a-z][a-z0-9_/-]*)['"`]/g)].map((m) => m[1].replace(/\/?$/, '/')),
        ];
        for (const lit of lits) if (!NOT_S3.test(lit.split('${')[0])) hits.push({ lit, dir: dir.split('/').pop(), file: f });
      }
    }
  }
  const keyLike = (lit) => /\.(json|jsonl)$/.test(lit) || lit.endsWith('/') || /\$\{|</.test(lit);
  const roots = new Set(hits.filter((h) => keyLike(h.lit)).map((h) => h.lit.split('/')[0]));
  const normalize = (lit) => {
    const base = lit.split(/\$\{|<|YYYY|…/)[0];
    if (base === lit && /\.(json|jsonl)$/.test(lit)) return lit;
    return base.split('/').filter(Boolean).slice(0, 2).join('/') + '/';
  };
  const found = new Map(); // prefix -> Set(lambda dir)
  for (const { lit, dir } of hits) {
    if (!roots.has(lit.split('/')[0])) continue;
    const p = normalize(lit);
    if (!found.has(p)) found.set(p, new Set());
    found.get(p).add(dir);
  }
  const ds = readFileSync(join(ROOT, 'project-docs/rules/DATA_STRATEGY.md'), 'utf8');
  const docRows = [];
  let inTable = false;
  for (const line of ds.split('\n')) {
    if (/^\|\s*Prefix\s*\|\s*Sole writer/.test(line)) { inTable = true; continue; }
    if (inTable && !line.startsWith('|')) inTable = false;
    if (!inTable || /^\|-/.test(line)) continue;
    const [prefixCell, writer, cadence, readers] = line.split('|').slice(1, -1).map((s) => s.trim());
    docRows.push({ prefixes: [...prefixCell.replace(/\([^)]*\)/g, '').matchAll(/`([^`]+)`/g)].map((m) => m[1]), writer, cadence, readers });
  }
  const covered = (p, docPrefixes) => docPrefixes.some((d) => d.startsWith(p) || p.startsWith(normalize(d)));
  let md = header('S3 prefixes (world bucket)', 'path-like string literals in each Lambda\'s `<dir>/src` (heuristic), ' + (live ? '`aws s3api list-objects-v2 --delimiter /` on the world bucket, ' : '') + 'the prefix table in `project-docs/rules/DATA_STRATEGY.md`');
  md += '\nThe world bucket name comes from each Lambda\'s env (`WORLD_BUCKET` and similar; see env-keys.md). The code scan is a heuristic over string literals (including env-var defaults); keys built entirely from variables are not found, and deployed zips that differ from the repo are not scanned. Templated keys are cut at the first variable.\n\n';
  md += '## Found in Lambda source\n\n';
  const allDoc = docRows.flatMap((r) => r.prefixes);
  md += table(['Prefix / key', 'Lambda dirs', 'Also in DATA_STRATEGY'],
    [...found.keys()].sort().map((p) => [code(p), [...found.get(p)].sort().join(', '), covered(p, allDoc) ? 'yes' : 'no'])) + '\n\n';
  if (live) {
    const codeTops = new Set([...found.keys()].map((p) => p.split('/')[0] + '/'));
    md += `## Live bucket \`${live.s3.bucket}\` (top two levels)\n\n`;
    md += table(['Top-level prefix', 'Second-level prefixes', 'Seen in Lambda source'], live.s3.tree.map((t) => [code(t.top), t.children.map((c) => code(c.slice(t.top.length))).join(' ') || '— (objects only)', codeTops.has(t.top) ? 'yes' : 'no'])) + '\n\n';
  }
  md += '## DATA_STRATEGY prefix table (documented intent)\n\n';
  md += table(['Prefix', 'Documented writer', 'Cadence', 'Readers'], docRows.map((r) => [r.prefixes.map(code).join(', '), r.writer, r.cadence, r.readers])) + '\n';
  files['s3-prefixes.md'] = md;

  // features.md: one section per feature folder, so a feature check starts in one place (its README links here).
  // Lambdas: functions.json `features` (product names; two differ from their folder). Storage: what those
  // Lambdas write — S3 prefixes found in a source file that also puts objects, DynamoDB tables named in a
  // write command (shared code in backend/shared is not attributed). Heuristic over repo source.
  const FOLDER = { today: 'home', stories: 'threads' };
  const featDir = join(SRC, 'features');
  const feats = readdirSync(featDir).filter((d) => statSync(join(featDir, d)).isDirectory()).sort();
  const featuresOf = (n) => (FUNCTIONS[n].features || []).map((f) => FOLDER[f] || f);
  const unknown = [...new Set(NAMES.flatMap(featuresOf))].filter((f) => f !== 'ops' && !feats.includes(f));
  const textOf = (() => { const cache = {}; return (f) => (cache[f] ??= readFileSync(f, 'utf8')); })();
  const S3_WRITE = /PutObjectCommand|CopyObjectCommand|\bputJson\b|\bputObj\b|\bs3PutJson\b/;
  const DDB_WRITE = /new\s+(?:Put|Update|Delete|BatchWrite|TransactWrite)(?:Item)?Command\s*\(/g;

  const s3Writes = (dir) => [...new Set(hits.filter((h) => h.dir === dir.split('/').pop() && roots.has(h.lit.split('/')[0]) && S3_WRITE.test(textOf(h.file))).map((h) => normalize(h.lit)))].sort();
  const tableWrites = (n) => {
    const srcs = lambdaSources(FUNCTIONS[n].dir);
    const dflt = {}; // env key -> code default
    const alias = {}; // const name -> env key
    const keys = new Set(); // every *TABLE env key the Lambda reads
    for (const f of srcs) {
      for (const m of textOf(f).matchAll(/process\.env\.(\w*TABLE)\b/g)) keys.add(m[1]);
      for (const m of textOf(f).matchAll(/process\.env\.(\w*TABLE)\s*\|\|\s*['"]([^'"]+)['"]/g)) dflt[m[1]] ??= m[2];
      for (const m of textOf(f).matchAll(/(?:const|let|var)\s+(\w+)\s*=\s*process\.env\.(\w*TABLE)\b/g)) alias[m[1]] = m[2];
    }
    const name = (key) => live?.tables[n]?.[key] || dflt[key] || `env ${key}`;
    const out = new Set();
    for (const f of srcs) {
      const t = textOf(f);
      for (const m of t.matchAll(DDB_WRITE)) {
        const win = t.slice(m.index, m.index + 300);
        const ref = win.match(/TableName:\s*(?:process\.env\.(\w+)|['"]([^'"]+)['"]|(\w+))/) || win.match(/RequestItems:\s*\{\s*\[(?:process\.env\.(\w+)|()(\w+))\]/);
        if (!ref) continue;
        if (ref[1]) out.add(name(ref[1]));
        else if (ref[2]) out.add(ref[2]);
        else if (alias[ref[3]]) out.add(name(alias[ref[3]]));
        // A table passed in as a parameter: unambiguous only when the Lambda reads one table key.
        else if (keys.size === 1) out.add(name([...keys][0]));
        else out.add('(table from a variable)');
      }
    }
    return [...out].sort();
  };

  const runbooks = readdirSync(join(ROOT, 'project-docs/runbooks')).filter((f) => f.endsWith('.md') && f !== 'README.md').sort();
  const runbookTitle = Object.fromEntries(runbooks.map((f) => [f, (readFileSync(join(ROOT, 'project-docs/runbooks', f), 'utf8').match(/^# .*$/m) || [''])[0]]));
  const word = (s) => new RegExp(`(?<![\\w-])${s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?![\\w-])`);
  const runbookOf = (n) => runbooks.filter((f) => word(n).test(runbookTitle[f]));

  const decisionsDir = join(ROOT, 'project-docs/decisions');
  const decisions = readdirSync(decisionsDir).filter((f) => /^\d{4}-.*\.md$/.test(f)).sort();
  // A decision belongs to a feature when its file name or text names the folder (`features/<name>`) or its text
  // names one of the feature's routes exactly.
  const routeTerm = (p) => {
    const esc = p.split('/:')[0].replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    return p.includes('/:') ? `${esc}/` : `${esc}(?![\\w/-])`;
  };
  const decisionsOf = (name, own) => {
    const terms = [`features/${name}(?![\\w-])`, ...own.filter((p) => p !== '/' && p !== '*').map(routeTerm)];
    const re = new RegExp(`(?<![\\w/.-])(?:${terms.join('|')})`);
    return decisions.filter((f) => f.includes(`-${name}-`) || re.test(readFileSync(join(decisionsDir, f), 'utf8')));
  };

  const appFiles = walk(join(SRC, 'app'), ['.js', '.jsx']);
  const summary = [];
  const sections = feats.map((name) => {
    const dir = join(featDir, name);
    const top = readdirSync(dir).filter((f) => /\.(jsx?|tsx?)$/.test(f) && !/\.test\./.test(f) && f !== 'index.js').sort();
    const own = routes.filter((r) => r.feature === name).map((r) => r.path);
    const appImporters = appFiles.filter((f) => new RegExp(`@/features/${name}['/]`).test(textOf(f))).map((f) => code(relative(join(SRC, '..'), f)));
    const indexFile = join(dir, 'index.js');
    const api = existsSync(indexFile) ? [...textOf(indexFile).matchAll(/export\s*\{([^}]+)\}/g)].flatMap((m) => m[1].split(',').map((s) => s.trim().split(/\s+as\s+/).pop())) : [];
    const fns = NAMES.filter((n) => featuresOf(n).includes(name));
    const decs = decisionsOf(name, own);
    const routeCell = own.length ? own.map(code).join(', ') : appImporters.length ? `none — imported by ${appImporters.join(', ')}` : 'none — imported by other features';
    summary.push([`[${name}](#${name})`, routeCell, fns.length]);

    const lines = [`## ${name}\n`];
    lines.push(`- Folder: ${code(`src/features/${name}`)}; routes: ${routeCell}`);
    lines.push(`- Entry files: ${top.map(code).join(', ') || '—'}`);
    lines.push(`- Public API (\`index.js\`): ${existsSync(indexFile) ? api.map(code).join(', ') || '—' : 'no index.js'}`);
    lines.push(`- Decisions: ${decs.length ? decs.map((f) => `[${f.slice(0, 4)}](../decisions/${f})`).join(', ') : '— (none name its folder or routes)'}`);
    lines.push('');
    if (!fns.length) { lines.push('No Lambda in functions.json lists this feature.'); return lines.join('\n'); }
    lines.push(table(['Lambda', 'Repo dir', 'Schedule (state)', 'Runbook', 'Writes S3', 'Writes DynamoDB'], fns.map((n) => {
      const f = FUNCTIONS[n];
      const sch = schedules.filter((s) => s.targets.includes(n)).map((s) => `${s.via === 'Scheduler' ? 'Scheduler' : 'rule'} ${s.name} ${code(s.expr)}${s.tz !== 'UTC' ? ` ${s.tz}` : ''} (${s.state})`);
      if (live?.url[n]?.length) sch.push('Function URL');
      const rb = runbookOf(n);
      return [
        code(n), f.dir ? code(f.dir) : '— (no repo source)', sch.join('; ') || '—',
        rb.map((r) => `[${r}](../runbooks/${r})`).join(', ') || '—',
        f.dir ? s3Writes(f.dir).map(code).join(' ') || '—' : '—',
        f.dir ? tableWrites(n).map(code).join(' ') || '—' : '—',
      ];
    })));
    return lines.join('\n');
  });
  let fmd = header('Frontend features', '`src/features/*`, routes from `src/app/App.jsx`, `features` lists in `scripts/functions.json`, Lambda source (S3/DynamoDB writes, heuristic), runbook titles, decision records' + (live ? ', schedules + `*TABLE` env values from live AWS' : ''));
  fmd += `\n${feats.length} feature folders under \`global-perspectives-starter/frontend/src/features/\`. Dependency direction (eslint \`no-restricted-imports\`): app → features → shared. Each folder's README.md is the front door and links to its section here.\n\n`;
  fmd += 'Lambdas: those whose `features` in functions.json name the folder (`today` = home, `stories` = threads); a row does not mean the page calls it directly — the read API Lambdas serve many features. Writes: S3 prefixes found in a source file that also puts objects; DynamoDB tables named in a Put/Update/Delete/BatchWrite command (`env KEY` when no name is known). Shared code in `backend/shared` and keys built only from variables are not attributed; deployed zips that differ from the repo are not scanned.\n\n';
  fmd += table(['Feature', 'Routes', 'Lambdas'], summary) + '\n\n';
  if (unknown.length) fmd += `functions.json names features with no folder: ${unknown.map(code).join(', ')}.\n\n`;
  fmd += sections.join('\n\n') + '\n';
  files['features.md'] = fmd;
}

mkdirSync(OUT, { recursive: true });
for (const [name, body] of Object.entries(files)) writeFileSync(join(OUT, name), body.replace(/\n+$/, '\n'));
